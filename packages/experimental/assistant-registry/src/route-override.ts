/**
 * Scoped model routing seam: step assembly, pre-step notices, and image checks
 * read the selection captured before assembly. A later route change selects the
 * next step and does not rewrite the captured provider, model, or effort.
 * @module @deepseek-ai/dsh-experimental-assistant-registry/route-override
 */

import type { Context } from '@deepseek-ai/cordis'
import type { Agent, PreStepDecision } from '@deepseek-ai/dsh-agent'
import type { PromptAssembly, AssembleContext } from '@deepseek-ai/dsh-system-prompt'
import {
  boundContextSummary,
  createUserMessage,
  LlmError,
  type LlmCallConfig,
  type UserMessage,
} from '@deepseek-ai/dsh-llm'
import type { AssistantService } from './index.ts'

/**
 * Compares two model selections for equality by provider and model.
 * @param left - left model selection.
 * @param right - right model selection.
 * @returns true if provider and model match.
 */
export function sameRoute(
  left: { readonly provider: string; readonly model: string },
  right: { readonly provider: string; readonly model: string },
): boolean {
  return left.provider === right.provider && left.model === right.model
}

/**
 * Formats user-facing label for a route switch.
 * @param route - target model route.
 * @param other - comparison model route.
 * @returns formatted model route label.
 */
export function routeLabel(
  route: { readonly provider: string; readonly model: string },
  other: { readonly provider: string; readonly model: string },
): string {
  return route.provider === other.provider ? route.model : `${route.provider}/${route.model}`
}

/**
 * Generates model change notice message.
 * @param previous - previous model route.
 * @param selected - newly selected model route.
 * @returns formatted notice UserMessage.
 */
export function modelSwitchNotice(
  previous: { readonly provider: string; readonly model: string },
  selected: { readonly provider: string; readonly model: string },
): UserMessage {
  const from = routeLabel(previous, selected)
  const to = routeLabel(selected, previous)
  return createUserMessage({
    content: [{
      type: 'text' as const,
      text: `[model changed: assistant turns above this point were generated by ${from}; the session continues with ${to}]`,
    }],
    source: {
      kind: 'model-selection',
      form: 'notice',
      summary: boundContextSummary(`${from} → ${to}`),
    },
  })
}

/**
 * Installs the prepended waterfall listeners for prompt assembly, pre-step notice,
 * and request routing on the root or host context.
 *
 * @param ctx - Cordis context to attach listeners to.
 * @param assistants - Assistant service owning catalog and route state.
 * @returns Disposer function for all installed listeners.
 */
export function installRouteOverride(ctx: Context, assistants: AssistantService): () => void {
  const disposeAssembly = ctx.on(
    'system-prompt/assemble',
    async (_assembly: PromptAssembly, context: AssembleContext, next: () => Promise<PromptAssembly>): Promise<PromptAssembly> => {
      const agent = context.agent
      const selected = context.modelSelection
      if (!agent || selected === undefined || !assistants.isAssistantBound(agent.id)) {
        return next()
      }
      assistants.assertSessionUsable(agent.id)

      const assembled = await next()
      assistants.clearAssembledSelection(agent.id)
      return {
        ...assembled,
        variables: {
          ...assembled.variables,
          provider: selected.provider,
          model: selected.model,
        },
      }
    },
    { prepend: true },
  )

  const disposePreStep = ctx.on(
    'agent/pre-step',
    async (
      payload: {
        agent: Agent
        messages: readonly UserMessage[]
        turn: number
        step: number
        signal: AbortSignal
        modelSelection: { readonly provider: string; readonly model: string }
      },
      next: () => Promise<PreStepDecision>,
    ): Promise<PreStepDecision> => {
      const { agent, messages, signal, step, modelSelection } = payload
      if (!assistants.isAssistantBound(agent.id)) {
        return next()
      }

      assistants.assertSessionUsable(agent.id)
      const sessionId = agent.id
      assistants.recordStepMessages(sessionId, messages)

      const decision = await next()
      if (decision.kind === 'reject' || signal.aborted) {
        return decision
      }
      if (decision.messages.length === 0 && (step === 1 || messages.length > 0)) {
        return decision
      }

      assistants.clearAssembledSelection(sessionId)
      const previous = agent.session.requestHeader()?.config
      const routeChanged = previous !== undefined && !sameRoute(previous, modelSelection)
      const kept = decision.messages.filter(message => message.source.kind !== 'model-selection')
      if (!routeChanged) return { ...decision, messages: kept }
      return { ...decision, messages: [...kept, modelSwitchNotice(previous, modelSelection)] }
    },
    { prepend: true },
  )

  const disposeRequest = ctx.on(
    'agent/request',
    async (
      payload: { agent: Agent; turn: number; step: number; signal: AbortSignal },
      next: () => Promise<LlmCallConfig>,
    ): Promise<LlmCallConfig> => {
      const { agent, signal } = payload
      if (!assistants.isAssistantBound(agent.id)) {
        return next()
      }

      assistants.assertSessionUsable(agent.id)
      const sessionId = agent.id
      const resolved = await next()
      if (assistants.requestCarriesImages(sessionId, agent.session)) {
        const modelInfo = await ctx.llm.resolveModelInfo(resolved.provider, resolved.model, signal)
        if (modelInfo.inputModalities?.includes('image') !== true) {
          throw new LlmError(
            `Route "${resolved.provider}:${resolved.model}" does not support image input`,
            'UNSUPPORTED_CONTENT',
          )
        }
      }
      return resolved
    },
    { prepend: true },
  )

  const disposeAgentCreated = ctx.on('agent/created', ({ agent }) => {
    if (assistants.isAssistantBound(agent.id)) {
      assistants.syncAgentSelection(agent.id)
    }
  })

  return () => {
    disposeAssembly()
    disposePreStep()
    disposeRequest()
    disposeAgentCreated()
  }
}
